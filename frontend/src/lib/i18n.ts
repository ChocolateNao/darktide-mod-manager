export type MessageKey = keyof typeof messages;

export type MessageVars = Record<string, string | number>;

const PLACEHOLDER = /\{(\w+)\}/g;

/**
 * Looks a key up and substitutes `{name}` placeholders. An unknown key returns
 * the key itself — a missing translation stays visible during development.
 */
export function t(key: MessageKey | (string & {}), vars?: MessageVars): string {
  const template: string = messages[key as MessageKey] ?? key;
  if (!vars) return template;
  return template.replace(PLACEHOLDER, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

/** Translate a key supplied by Go, falling back to Go's English when absent. */
export function tOr(
  key: string | undefined,
  fallback: string,
  vars?: MessageVars
): string {
  if (!key || !(key in messages)) return fallback;
  return t(key, vars);
}
